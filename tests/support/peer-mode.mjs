/**
 * Where the DSH peer packages reachable right now came from, and what that
 * qualifies a suite to claim.
 *
 * A stub root (tests/peer-stubs.mjs) is enough for the plugin's own logic, but
 * three suites exercise the host's framework itself — Cordis service ordering,
 * profile boot, and the tool schema compiler. A stubbed `dsh-fs` has no
 * `assertSupportedJsonSchema`, and a stubbed `cordis` has no `Context`. Those
 * suites must SKIP (with a reason) rather than crash or silently "pass": a crash
 * reads as a broken build, and a false pass hides a real one.
 *
 * There are FOUR outcomes per package, and collapsing them loses the only thing
 * a reader can act on:
 *
 *   real    the host's own package; the suite's evidence is meaningful
 *   stub    a shape-only stand-in generated by tests/peer-stubs.mjs; SKIP
 *   absent  nothing resolved at that specifier; SKIP
 *   broken  it RESOLVED but threw while loading — a damaged tree, not a
 *           missing one. This one FAILS: skipping a damaged tree hides a
 *           dependency problem behind a green run, which is the exact failure
 *           this harness exists to prevent. It is also what the old ad-hoc
 *           check in boot-smoke.mjs got wrong: a directory that exists but
 *           cannot load was reported as "not in the core tree", sending the
 *           reader to install a package that is already installed.
 *
 * The whole-tree summary adds `mixed`: some packages are the host's own and some
 * are not. In this repository the generator always writes a whole tree, so mixed
 * was theoretical — but it is the default shape of a user's `node_modules`, and
 * the old detector answered `real: true` for it because it only inspected
 * `dsh-fs`. A suite then crashed in the one place it needed the stubbed package.
 *
 * `skipWithoutRealPeers()` takes the per-suite list of packages the suite
 * actually needs, so a tree missing an unrelated peer does not skip work that
 * could have run.
 *
 * @module tests/support/peer-mode
 */

import { createRequire } from 'node:module'
import path from 'node:path'

/** The host packages every generated stub root stands in for. */
export const HOST_PEERS = Object.freeze([
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-fs',
  '@deepseek-ai/dsh-tools',
])

/** The four outcomes a single-package probe can return. */
export const PACKAGE_STATE = Object.freeze({
  REAL: 'real',
  STUB: 'stub',
  ABSENT: 'absent',
  BROKEN: 'broken',
})

/** The whole-tree summaries `describeTree()` can return. */
export const TREE_MODE = Object.freeze({
  REAL: 'real',
  STUB: 'stub',
  MIXED: 'mixed',
  ABSENT: 'absent',
  BROKEN: 'broken',
})

/** A requirement entry: a bare name, or `{ name, introspect: false }`. */
function normaliseRequirement (entry) {
  if (typeof entry === 'string') return { name: entry, introspect: true }
  return { introspect: true, ...entry }
}

/** Render an error as one line, because it is printed under an assertion. */
function describeError (error) {
  const message = error instanceof Error ? error.message : String(error)
  return message.replace(/\s+/gu, ' ').trim()
}

/**
 * Describe one package as seen from a peer root.
 *
 * Resolution and loading are asked separately on purpose. `require.resolve()`
 * answering proves the specifier exists; it does not prove the package can load.
 * A missing TRANSITIVE peer resolves fine and then throws — reporting that as
 * "not installed" sends the reader to install a package that is already there,
 * while naming the package that is actually missing sends them to the fix.
 *
 * @param {string} root - a `node_modules` directory (`DSH_CORE_ROOT`'s shape).
 * @param {string} name - the package specifier to probe.
 * @param {{introspect?: boolean}} [options] - `introspect: false` stops after a
 *   successful resolve; use it for ESM-only host packages that cannot be
 *   `require()`d, where resolution is all this detector can honestly prove.
 * @returns {{name: string, state: string, resolved: string|null, error: string|null, esm?: boolean}}
 */
export function describePackage (root, name, options = {}) {
  const introspect = options.introspect !== false
  const requireFromRoot = createRequire(path.join(root, 'noop.cjs'))

  let resolved
  try {
    resolved = requireFromRoot.resolve(name)
  } catch {
    return { name, state: PACKAGE_STATE.ABSENT, resolved: null, error: null }
  }
  if (!introspect) {
    return { name, state: PACKAGE_STATE.REAL, resolved, error: null }
  }

  let loaded
  try {
    loaded = requireFromRoot(name)
  } catch (error) {
    // An ESM-only package is not a broken one. The stubs are CommonJS, so a
    // resolved ESM entry point cannot be one of ours; resolution is the proof.
    if (error?.code === 'ERR_REQUIRE_ESM' || error?.code === 'ERR_REQUIRE_ASYNC_MODULE') {
      return { name, state: PACKAGE_STATE.REAL, resolved, error: null, esm: true }
    }
    return { name, state: PACKAGE_STATE.BROKEN, resolved, error: describeError(error) }
  }
  if (loaded !== null && typeof loaded === 'object' && loaded.__dshStub === true) {
    return { name, state: PACKAGE_STATE.STUB, resolved, error: null }
  }
  return { name, state: PACKAGE_STATE.REAL, resolved, error: null }
}

/**
 * Collapse per-package states into one word.
 *
 * `stub` is "no package here is the host's own, and at least one is a stub" —
 * that is the generated root by construction, and calling it `mixed` would
 * imply a hazard it does not have. `mixed` is reserved for a tree that pairs a
 * real package with a non-real one, which is the genuinely dangerous shape.
 *
 * @param {Array<{state: string}>} packages - probe results.
 * @returns {string} one of TREE_MODE.
 */
function summarise (packages) {
  const states = packages.map(entry => entry.state)
  if (states.length === 0) return TREE_MODE.ABSENT
  if (states.includes(PACKAGE_STATE.BROKEN)) return TREE_MODE.BROKEN
  if (states.every(state => state === PACKAGE_STATE.REAL)) return TREE_MODE.REAL
  if (states.every(state => state === PACKAGE_STATE.ABSENT)) return TREE_MODE.ABSENT
  if (states.every(state => state === PACKAGE_STATE.STUB)) return TREE_MODE.STUB
  if (!states.includes(PACKAGE_STATE.REAL) && states.includes(PACKAGE_STATE.STUB)) return TREE_MODE.STUB
  return TREE_MODE.MIXED
}

/**
 * Describe a peer root, package by package.
 *
 * @param {string|undefined} root - the `DSH_CORE_ROOT` value.
 * @param {Array<string|{name: string, introspect?: boolean}>} [requirements]
 * @returns {{root: string|null, packages: Array<object>, mode: string, reason: string}}
 */
export function describeTree (root, requirements = HOST_PEERS) {
  if (root === undefined || root === null || root === '') {
    return { root: null, packages: [], mode: TREE_MODE.ABSENT, reason: 'DSH_CORE_ROOT is not set' }
  }
  const resolvedRoot = path.resolve(root)
  const packages = requirements
    .map(normaliseRequirement)
    .map(requirement => describePackage(resolvedRoot, requirement.name, requirement))
  const mode = summarise(packages)
  const summary = packages.map(entry => `${entry.name}=${entry.state}`).join(', ')
  return {
    root: resolvedRoot,
    packages,
    mode,
    reason: mode === TREE_MODE.REAL ? '' : `${resolvedRoot}: ${summary}`,
  }
}

/**
 * Whether the DSH peer packages reachable right now are the host's own.
 *
 * `real` is true only when every probed package is real. A tree with one real
 * package and one stub is `mixed`, not `real` — the old detector asked only
 * about `dsh-fs` and then let a suite crash on the stub it never looked at.
 *
 * @returns {{real: boolean, mode: string, reason: string, root: string|null, packages: Array<object>}}
 */
export function peerMode () {
  const tree = describeTree(process.env.DSH_CORE_ROOT, HOST_PEERS)
  return { ...tree, real: tree.mode === TREE_MODE.REAL }
}

/**
 * Proceed only when every package this suite needs is the host's own.
 *
 * Outcomes:
 *   - all required packages real  → returns, the suite runs;
 *   - any required package broken → prints the failing package AND its load
 *     error, then exits 1. A damaged tree is a setup defect, and skipping it
 *     would report "nothing to run" for something that is actively wrong;
 *   - any required package stub or absent → prints a SKIP naming which package
 *     is in which state, then exits 0.
 *
 * `needs` names the capability in prose; the package list comes from
 * `options.requires` so each suite declares only what it actually uses.
 *
 * @param {string} suiteName - the suite's display name.
 * @param {string} needs - what it requires, for the message.
 * @param {{requires?: Array<string|{name: string, introspect?: boolean}>}} [options]
 * @returns {void} never returns on a skip or a failure (exits the process).
 */
export function skipWithoutRealPeers (suiteName, needs, options = {}) {
  const requirements = options.requires ?? HOST_PEERS
  const tree = describeTree(process.env.DSH_CORE_ROOT, requirements)
  if (tree.mode === TREE_MODE.REAL) return

  const broken = tree.packages.filter(entry => entry.state === PACKAGE_STATE.BROKEN)
  if (broken.length > 0) {
    console.log(`\n=== ${suiteName} ===\n`)
    console.log(`  FAIL  the DSH tree at ${tree.root} is installed but cannot be loaded`)
    for (const entry of broken) console.log(`        ${entry.name}: ${entry.error}`)
    console.log('        This is a DAMAGED dependency tree, not a missing one. Skipping would')
    console.log('        report a green run for a setup that is actively wrong. Fix the package')
    console.log('        named above (it resolved from disk, then failed to load), or unset')
    console.log('        DSH_CORE_ROOT to run against the generated stub root.')
    console.log('\n=== 0 passed, 1 failed, 0 suites skipped ===')
    process.exit(1)
  }

  console.log(`\n=== ${suiteName} ===\n`)
  console.log(`  SKIP  needs ${needs} (${tree.reason})`)
  console.log('\n=== 0 passed, 0 failed, 1 suite skipped ===')
  process.exit(0)
}
